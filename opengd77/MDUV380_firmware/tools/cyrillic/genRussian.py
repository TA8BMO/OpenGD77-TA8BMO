#!/usr/bin/env python3
"""Builds application/include/user_interface/languages/russian.h.

english.h is the template: every field, its order and its comments come from
there, and each string listed in russian_table.txt replaces the English one.
The text is written as Windows-1251 escapes, which is what the Cyrillic fonts
in HX8353E_charset_cyrillic.h are indexed by, so the header stays plain ASCII.

Every string is checked against the 16 bytes a field holds; a string longer than
the MaxLen noted in english.h is reported, since that MaxLen is what fits the
screen with the value that follows it.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LANG = os.path.normpath(os.path.join(HERE, "..", "..", "application", "include", "user_interface", "languages"))


def c_literal(text):
    raw = text.encode("cp1251")
    out = '"'
    prev_hex = False
    for b in raw:
        ch = chr(b)
        if b >= 0x80 or b < 0x20:
            out += "\\x%02X" % b
            prev_hex = True
            continue
        if prev_hex and ch in "0123456789abcdefABCDEF":
            out += '""'
        if ch in '"\\':
            out += "\\"
        out += ch
        prev_hex = False
    return out + '"'


def main():
    table = {}
    for line in open(os.path.join(HERE, "russian_table.txt"), encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        field, text = line.split("\t")
        table[field] = text

    src = open(os.path.join(LANG, "english.h"), encoding="latin-1").read()
    fields_seen = set()
    warnings = []

    def repl(m):
        indent, field, gap, value, rest = m.groups()
        fields_seen.add(field)
        if field not in table:
            return m.group(0)
        text = table[field]
        n = len(text.encode("cp1251"))
        if n > 16:
            raise SystemExit("%s: '%s' is %d bytes, the field holds 16" % (field, text, n))
        lim = re.search(r"max\s*len:?\s*(\d+)", rest, re.I)
        if lim and n > int(lim.group(1)):
            warnings.append("%s: '%s' is %d, MaxLen %s" % (field, text, n, lim.group(1)))
        return indent + "." + field + gap + c_literal(text) + rest

    out = re.sub(r'(?m)^(\s*)\.([A-Za-z0-9_]+)(\s*=\s*)("(?:[^"\\]|\\.)*")(.*)$', repl, src)

    unknown = set(table) - fields_seen
    if unknown:
        raise SystemExit("not fields of stringsTable_t: %s" % ", ".join(sorted(unknown)))

    out = out.replace("USER_INTERFACE_LANGUAGES_ENGLISH_H_", "USER_INTERFACE_LANGUAGES_RUSSIAN_H_")
    out = out.replace("englishLanguage", "russianLanguage")
    out = out.replace("/********************************************************************\n *\n * VERY IMPORTANT.",
                      "/*\n * Russian, by TA8BMO. Generated by tools/cyrillic/genRussian.py from english.h and\n"
                      " * russian_table.txt - change those and run the script rather than editing this.\n"
                      " * The text is Windows-1251 (see HX8353E_charset_cyrillic.h).\n */\n"
                      "/********************************************************************\n *\n * VERY IMPORTANT.", 1)
    if "russianLanguage" not in out:
        raise SystemExit("could not rename the table")

    open(os.path.join(LANG, "russian.h"), "w", encoding="latin-1", newline="\n").write(out)
    print("russian.h: %d of %d strings in Russian" % (len(table), len(fields_seen)))
    for w in warnings:
        print("  over MaxLen:", w)


if __name__ == "__main__":
    main()
