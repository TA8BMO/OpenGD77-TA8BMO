#!/usr/bin/env python3
"""Builds application/include/hardware/HX8353E_charset_cyrillic.h from glyphs.txt.

The radio's fonts are Latin-1 based and every one of their 223 places is taken,
so Cyrillic gets fonts of its own: 66 letters per size, in Windows-1251 order
(0xC0-0xFF = A..ya, then Yo 0xA8 and yo 0xB8). The display driver uses them
for those codes while the radio is in Russian (see HX8353E_display.c).

Letters that look the same as Latin ones are copied from the Latin glyphs of the
same font, so a Russian "A" is pixel for pixel the Latin "A".

Usage:  python genCyrillic.py            write the header
        python genCyrillic.py preview    also print every glyph as text
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.normpath(os.path.join(HERE, "..", "..", "application", "include", "hardware"))
CHARSET = os.path.join(INC, "HX8353E_charset.h")
OUT = os.path.join(INC, "HX8353E_charset_cyrillic.h")

UPPER = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
LOWER = "абвгдежзийклмнопрстуфхцчшщъыьэюя"
ORDER = UPPER + LOWER + "Ёё"           # index 0..63 = 0xC0..0xFF, 64 = 0xA8, 65 = 0xB8
LATIN = {"А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "О": "O", "Р": "P",
         "С": "C", "Т": "T", "Х": "X", "Ё": "\xCB",
         "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x", "ё": "\xEB"}
# transliteration, for the comments in the generated (plain ASCII) header
TRANSLIT = dict(zip(ORDER, ["A", "B", "V", "G", "D", "E", "Zh", "Z", "I", "J", "K", "L", "M", "N", "O", "P",
                            "R", "S", "T", "U", "F", "H", "Ts", "Ch", "Sh", "Sch", "Hard", "Y", "Soft", "Ee", "Yu", "Ya",
                            "a", "b", "v", "g", "d", "e", "zh", "z", "i", "j", "k", "l", "m", "n", "o", "p",
                            "r", "s", "t", "u", "f", "h", "ts", "ch", "sh", "sch", "hard", "y", "soft", "ee", "yu", "ya",
                            "Yo", "yo"]))

FONTS = {  # name in glyphs.txt -> (Latin array, width, height)
    "font6": ("font_6x8", 6, 8),
    "font8": ("font_8x8", 8, 8),
    "font16": ("font_8x16", 8, 16),
}


def load_latin(name):
    s = open(CHARSET, encoding="latin-1").read()
    m = re.search(r"const uint8_t " + name + r"\[\] = \{(.*?)\n\};", s, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|[0-9]+", body)]


def latin_rows(font, code, w, h):
    start, bpc = font[2], font[7]
    data = font[8 + (code - start) * bpc:][:bpc]
    return ["".join("#" if (data[x + (y // 8) * w] >> (y % 8)) & 1 else "." for x in range(w)) for y in range(h)]


def parse_glyphs():
    glyphs = {}
    cur = None
    for line in open(os.path.join(HERE, "glyphs.txt"), encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("#") and not set(line) <= set("#."):
            continue  # a comment (a pixel row is only '#' and '.')
        if line.startswith("== "):
            _, font, letter = line.split()
            cur = {"font": font, "rows": [], "start": 0}
            glyphs[(font, letter)] = cur
            continue
        if cur is None or not line.strip():
            continue
        if line.startswith("@"):
            cur["start"] = int(line[1:])
            continue
        cur["rows"].append(line)
    return glyphs


def build():
    glyphs = parse_glyphs()
    tables = {}
    previews = {}
    for fname, (latin_name, w, h) in FONTS.items():
        latin = load_latin(latin_name)
        data = []
        prev = []
        for letter in ORDER:
            if letter in LATIN:
                rows = latin_rows(latin, ord(LATIN[letter]), w, h)
                if (fname, letter) in glyphs:
                    raise SystemExit("%s %s is drawn but also copied from Latin" % (fname, letter))
            else:
                g = glyphs.get((fname, letter))
                if g is None:
                    raise SystemExit("missing glyph: %s %s" % (fname, letter))
                rows = ["." * w] * h
                for i, r in enumerate(g["rows"]):
                    y = g["start"] + i
                    if y >= h or len(r) > w - 1:
                        raise SystemExit("%s %s: row %d '%s' is outside the cell" % (fname, letter, y, r))
                    rows[y] = r.ljust(w, ".")
            cols = []
            for page in range(h // 8):
                for x in range(w):
                    b = 0
                    for bit in range(8):
                        if rows[page * 8 + bit][x] == "#":
                            b |= (1 << bit)
                    cols.append(b)
            data.append((letter, cols))
            prev.append(rows)
        tables[fname] = data
        previews[fname] = prev
    return tables, previews


def write(tables):
    o = []
    o.append("// Auto-generated by tools/cyrillic/genCyrillic.py from glyphs.txt - do not edit by hand.")
    o.append("//")
    o.append("// Cyrillic letters for the 6x8, 8x8 and 8x16 fonts, 66 per font in Windows-1251")
    o.append("// order: 0xC0-0xFF, then 0xA8 (Yo) and 0xB8 (yo). Column bytes, bit 0 at the top,")
    o.append("// laid out exactly like the Latin fonts in HX8353E_charset.h. They live in the")
    o.append("// flash after the codec (.hiconst), where there is room.")
    o.append("#ifndef _OPENGD77_HX8353E_CHARSET_CYRILLIC_H_")
    o.append("#define _OPENGD77_HX8353E_CHARSET_CYRILLIC_H_")
    o.append("")
    o.append("#include <stdint.h>")
    o.append("")
    o.append("#define CYRILLIC_GLYPH_COUNT 66")
    o.append("")
    names = {"font6": ("cyrillicFont6x8", 6), "font8": ("cyrillicFont8x8", 8), "font16": ("cyrillicFont8x16", 16)}
    for fname, (cname, bpc) in names.items():
        o.append("static const uint8_t %s[CYRILLIC_GLYPH_COUNT * %d] __attribute__((section(\".hiconst\"))) =" % (cname, bpc))
        o.append("{")
        for letter, cols in tables[fname]:
            o.append("\t" + ", ".join("0x%02x" % b for b in cols) + ", // " + TRANSLIT[letter])
        o.append("};")
        o.append("")
    o.append("#endif")
    open(OUT, "w", encoding="ascii", newline="\n").write("\n".join(o) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    t, p = build()
    write(t)
    if len(sys.argv) > 1 and sys.argv[1] == "preview":
        for fname, prev in p.items():
            print("=====", fname)
            for start in range(0, len(ORDER), 11):
                chunk = prev[start:start + 11]
                print("   ".join(("%-" + str(len(chunk[0][0])) + "s") % TRANSLIT[ORDER[start + i]][:len(chunk[0][0])] for i in range(len(chunk))))
                for y in range(len(chunk[0])):
                    print("   ".join(g[y] for g in chunk))
                print()
